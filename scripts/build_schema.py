"""Bundle ordered SQL migrations for one paste into a new Supabase SQL Editor."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    migrations = sorted((ROOT / 'supabase' / 'migrations').glob('*.sql'))
    sections = ['-- ApnaGhar database setup. Generated by scripts/build_schema.py.\n'
                '-- Run in your own Supabase project SQL Editor.\n'
                '-- Includes migrations 001 through 006; do not also run them separately.\n']
    for migration in migrations:
        sections.append(f'\n-- BEGIN {migration.name}\n' + migration.read_text(encoding='utf-8')
                        + f'\n-- END {migration.name}\n')
    destination = ROOT / 'supabase' / 'setup.sql'
    destination.write_text('\n'.join(sections), encoding='utf-8')
    print(f'Bundled {len(migrations)} migrations into supabase/setup.sql. No database was contacted.')


if __name__ == '__main__':
    main()
